// First selected language: used for date formats and the page's lang attribute.
export function getLang() { return current[0]; }
export function getLangs() { return [...current]; }

export function setLangs(langs) {
  const valid = UI_LANGS.filter((l) => (langs || []).includes(l));
  current = valid.length ? valid : ['en'];
  document.documentElement.lang = current[0];
  applyI18n();
}

function one(lang, key, vars) {
  let s = S[lang]?.[key] ?? S.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

export function t(key, vars) {
  const parts = [];
  for (const l of current) {
    const s = one(l, key, vars);
    if (!parts.includes(s)) parts.push(s); // e.g. "Perspective" is the same in English and French
  }
  return parts.join(' / ');
}

// Same as t(), but only in the first interface language: for short texts on the
// tree cards, where "32 years old / 32 ans / 32 წლის" would not fit.
export function tFirst(key, vars) {
  return one(current[0], key, vars);
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((e) => { e.textContent = t(e.dataset.i18n); });
  // Short labels (toolbar): first interface language only, so they stay short.
  root.querySelectorAll('[data-i18n-first]').forEach((e) => { e.textContent = tFirst(e.dataset.i18nFirst); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((e) => { e.placeholder = t(e.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach((e) => {
    e.title = t(e.dataset.i18nTitle);
    e.setAttribute('aria-label', e.title);
  });
  if (root === document) document.title = one(current[0], 'appTitle');
}
